export const findSmartphoneBySlug = (slug: string): Smartphone | undefined => {
  if (!slug) return undefined;
  let normalized = "";
  try {
    normalized = decodeURIComponent(slug).toLowerCase().trim();
  } catch {
    normalized = String(slug).toLowerCase().trim();
  }
  return allSmartphones.find(
    (p) =>
      p.slug.toLowerCase() === normalized ||
      p.slugAliases?.some((alias) => alias.toLowerCase() === normalized)
  );
};

export const getSmartphonesByBrand = (brand: string, excludeId?: string): Smartphone[] => {
  return allSmartphones.filter(
    (p) => p.brand.toLowerCase() === brand.toLowerCase() && p.id !== excludeId
  );
};
